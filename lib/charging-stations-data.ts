// Calculate map coordinates for all stations
export const STATIONS_WITH_COORDS = CHARGING_STATIONS.map((station) => ({
  ...station,
  mapX: lngToX(station.longitude),
  mapY: latToY(station.latitude),
}));

// Group stations by district
export const STATIONS_BY_DISTRICT = STATIONS_WITH_COORDS.reduce(
  (acc, station) => {
    if (!acc[station.district]) {
      acc[station.district] = [];
    }
    acc[station.district].push(station);
    return acc;
  },
  {} as Record<string, ChargingStation[]>
);

export const DISTRICTS = Object.keys(STATIONS_BY_DISTRICT).sort();
