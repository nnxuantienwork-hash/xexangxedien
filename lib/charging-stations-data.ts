// Charging stations data for HCMC extracted from CSV
// Coordinates are approximate based on district/neighborhood information
// Format: latitude, longitude (HCMC center is approximately 10.7769, 106.7009)

export interface ChargingStation {
  id: number;
  name: string;
  address: string;
  district: string;
  ports: string;
  latitude: number;
  longitude: number;
  mapX: number; // Percentage from left (0-100)
  mapY: number; // Percentage from top (0-100)
}

// HCMC district coordinate boundaries (approximate percentages on map)
// Left: 106.38, Right: 107.02, Top: 10.99, Bottom: 10.50
const HCMC_BOUNDS = {
  minLat: 10.50,
  maxLat: 10.99,
  minLng: 106.38,
  maxLng: 107.02,
};

const latToY = (lat: number): number => {
  return ((HCMC_BOUNDS.maxLat - lat) / (HCMC_BOUNDS.maxLat - HCMC_BOUNDS.minLat)) * 100;
};

const lngToX = (lng: number): number => {
  return ((lng - HCMC_BOUNDS.minLng) / (HCMC_BOUNDS.maxLng - HCMC_BOUNDS.minLng)) * 100;
};


